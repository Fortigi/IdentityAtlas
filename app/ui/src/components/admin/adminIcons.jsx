// Small inline-SVG icon set for the Admin section headers.
//
// Replaces the emoji-as-icon the audit flagged (M3 — 📦📊🏢🎯 on the Admin
// sections, plus the ⚠️ on the Danger Zone) with one consistent, theme-aware
// icon style: heroicons-outline geometry drawn with `currentColor`, so each
// icon inherits the surrounding text colour in both light and dark mode.
//
// Every icon takes an optional `className` (default `w-5 h-5`) so callers can
// resize without redefining the SVG.

function Icon({ className = 'w-5 h-5', title, children }) {
  return (
    <svg
      className={className}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {title && <title>{title}</title>}
      {children}
    </svg>
  );
}

