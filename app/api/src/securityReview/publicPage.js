// Renders the public summary of a monthly security review and adds it to the
// assessment history on docs/security/index.md.
//
// What is public follows the rule on that page: every finding is listed with
// its severity and OWASP category, but the write-up of a Medium-or-higher
// finding is withheld until it is fixed. Only Low and Informational findings
// show their one-line public summary. The page reaches the docs site through a
// pull request, so a maintainer reads it before it is published.

import { OWASP_TOP10, PRIVATE_SEVERITIES, SEVERITIES, countBySeverity } from './findings.js';

export const ROWS_MARKER = '<!-- security-review-rows -->';

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export function monthName(reviewId) {
  const [year, month] = reviewId.split('-');
  return `${MONTHS[Number(month) - 1]} ${year}`;
}

export function pageFileName(reviewId) {
  return `review-${reviewId}.md`;
}

// A table cell must not break the table or smuggle in markup. Backslashes are
// escaped first: otherwise a `\` in the input would cancel the `\|` added below
// and turn the pipe back into a column break.
export function cell(text) {
  return String(text)
    .replace(/\\/g, '\\\\')
    .replace(/\r?\n/g, ' ')
    .replace(/\|/g, '\\|')
    .replace(/</g, '&lt;');
}

function summaryFor(f) {
  return PRIVATE_SEVERITIES.has(f.severity) ? 'Details withheld until fixed' : cell(f.publicSummary);
}

function trackingFor(f, filings) {
  const url = filings[f.fingerprint]?.issueUrl;
  if (!url) return '—';
  const number = url.match(/\/issues\/(\d+)$/)?.[1];
  return number ? `[#${number}](${url})` : `[tracking](${url})`;
}

function countsTable(counts) {
  const rows = SEVERITIES.map(s => `| ${s} | ${counts[s]} |`);
  const total = SEVERITIES.reduce((n, s) => n + counts[s], 0);
  return ['| Severity | Found |', '|---|---:|', ...rows, `| **Total** | **${total}** |`].join('\n');
}

function coverageTable(coverage, findings) {
  const rows = Object.entries(OWASP_TOP10).map(([key, name]) => {
    const n = findings.filter(f => f.owasp === key).length;
    const notes = coverage.find(c => c.category === key)?.notes ?? '';
    return `| ${key} ${name} | ${n} | ${cell(notes)} |`;
  });
  return ['| OWASP Top 10 (2025) | Findings | What was checked |', '|---|---:|---|', ...rows].join('\n');
}

function findingsTable(findings, filings) {
  if (findings.length === 0) return 'No findings.';
  const rows = findings.map(f => `| ${f.id} | ${f.severity} | ${f.owasp} | ${summaryFor(f)} | ${trackingFor(f, filings)} |`);
  return ['| ID | Severity | OWASP | Summary | Tracking |', '|---|---|---|---|---|', ...rows].join('\n');
}

export function renderPublicPage(report, filings = {}) {
  const month = monthName(report.reviewId);
  const counts = countBySeverity(report.findings);
  return [
    '---\ntype: reference\n---',
    `# Monthly security review — ${month}`,
    `The automated monthly security review of Identity Atlas \`${cell(report.version)}\` (commit \`${report.commit.slice(0, 9)}\`). ` +
      'How it works, what it covers and how findings are handled is described in the [Security testing programme](index.md).',
    '!!! info "What is published"\n    Every finding is listed with its severity and OWASP category. The write-up of a Medium-or-higher finding is withheld until it is fixed; ' +
      'it is tracked in a private security advisory, and its public issue only says that it exists.',
    `## Result at a glance\n\n${countsTable(counts)}`,
    `## OWASP Top 10 coverage\n\n${coverageTable(report.coverage, report.findings)}`,
    `## Findings\n\n${findingsTable(report.findings, filings)}`,
    '---\n\n*Generated by the monthly security review workflow and checked by a maintainer before publication.*',
  ].join('\n\n') + '\n';
}

export function historyRow(report) {
  const counts = countBySeverity(report.findings);
  const found = SEVERITIES.filter(s => counts[s] > 0).map(s => `${counts[s]} ${s}`).join(', ') || 'No findings';
  const open = report.findings.filter(f => PRIVATE_SEVERITIES.has(f.severity)).length;
  const result = open === 0 ? 'No Medium or higher findings' : `${open} Medium or higher, tracked privately`;
  const month = monthName(report.reviewId);
  return `| ${month} | Monthly automated review | ${cell(report.version)}, \`${report.commit.slice(0, 9)}\` | ${found} | ${result} | [Review, ${month}](${pageFileName(report.reviewId)}) |`;
}

/**
 * Add (or replace) this review's row in the table that follows the marker,
 * as its first row, so the newest review is on top. The marker sits on the line
 * above the table: a comment inside a Markdown table would end the table.
 */
export function updateIndex(indexMd, report) {
  const link = `](${pageFileName(report.reviewId)})`;
  const lines = indexMd.split('\n').filter(line => !(line.startsWith('|') && line.includes(link)));
  const at = lines.indexOf(ROWS_MARKER);
  if (at === -1) throw new Error(`docs/security/index.md has no ${ROWS_MARKER} line`);
  if (!lines[at + 1]?.startsWith('|') || !/^\|[-:| ]+\|$/.test(lines[at + 2] ?? '')) {
    throw new Error(`${ROWS_MARKER} must be followed by a table header and separator`);
  }
  lines.splice(at + 3, 0, historyRow(report));
  return lines.join('\n');
}
