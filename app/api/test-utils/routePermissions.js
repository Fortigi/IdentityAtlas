// What every route of the app requires — the committed expectation the route ×
// role matrix (auth/routeRoleMatrix.test.js) and the per-route pin
// (auth/routePermissionTable.test.js) hold the real app to.
//
// One entry per route, keyed exactly as test-utils/routeSweep.js lists it
// ("<METHOD> <router pattern>"), in router order. The value is:
//   - an array: the permissions that open the route. Holding ANY ONE of them is
//     enough (requirePermission's any-of rule); a caller with none is refused 403.
//   - ANY: any signed-in caller who holds at least one permission. These routes
//     carry no gate of their own (or one listing every permission); the only
//     refusal is the deny-by-default 403 for a caller with none (F-01).
//   - CRAWLER_KEY: reachable with a crawler API key only. A user's token is
//     refused 401 whatever its roles — the Admin wildcard included.
// The routes that answer everybody (PUBLIC_ROUTES) or nobody (NEVER_DATA) are
// pinned in routeSweep.js and are deliberately not repeated here.
//
// This table is written down, not derived. The tests compare it with what the
// running app does, so it cannot quietly agree with a wrong gate: a new route
// without an entry fails, a removed route leaves a stale entry that fails, and a
// gate that changes fails until this file changes with it — on purpose, in the
// same diff a reviewer reads. When you add a route, add its line here and say
// which permission it needs; do not copy what the code happens to do.
//
// First generated from the code (Nov 2026) and then read route by route. Entries
// that are deliberate but worth knowing are marked "NOTE".

