<#
.SYNOPSIS
    Shared helpers for the release test (.github/workflows/release-test.yml).

.DESCRIPTION
    Dot-source this file. Everything here is a small function with no hidden
    state, so test/unit/ReleaseTestFunctions.Tests.ps1 can exercise it without
    Docker. The scripts that drive Docker, the portable ZIPs and Azure
    (Invoke-*ReleaseTest.ps1) call these and add only the side effects.

    A "candidate" is what the release test is asked to test: a version tag
    (v6.2.0-beta.1, v6.1.2) or the floating `edge` channel.
#>

Set-StrictMode -Version Latest

$script:CandidatePattern = '^(edge|v\d+\.\d+\.\d+(-(beta|rc|alpha)\.\d+)?)$'

# Synced data: an upgrade or a restore must keep exactly these rows. A
# migration that drops or duplicates one is the regression this test exists for.
$script:StrictTables = @(
    'Systems', 'Principals', 'Resources', 'ResourceAssignments',
    'ResourceRelationships', 'Identities', 'IdentityMembers'
)
# Generated by context plugins, which a newer version may add to. Fewer rows
# after an upgrade is still a failure; more is allowed.
$script:GrowOnlyTables = @('Contexts', 'ContextMembers')

function Get-Prop {
    <# A property of an API reply, or $null when the reply lacks it (StrictMode-safe). #>
    [CmdletBinding()]
    param($Object, [Parameter(Mandatory)][string] $Name)
    if ($null -eq $Object) { return $null }
    $p = $Object.PSObject.Properties[$Name]
    if ($p) { return $p.Value }
    return $null
}

function Assert-Candidate {
    [CmdletBinding()]
    param([Parameter(Mandatory)][string] $Candidate)
    if ($Candidate -notmatch $script:CandidatePattern) {
        throw "Candidate '$Candidate' is not 'edge' or a version tag like v6.2.0-beta.1."
    }
}

function ConvertTo-ImageTag {
    <# The Docker image tag docker-publish.yml pushes for a candidate. #>
    [CmdletBinding()]
    [OutputType([string])]
    param([Parameter(Mandatory)][string] $Candidate)
    Assert-Candidate $Candidate
    if ($Candidate -eq 'edge') { return 'edge' }
    $version = $Candidate.Substring(1)
    if ($version -match '-') { return $version }   # pre-release: 6.2.0-beta.1
    return "$version.0"                            # release: 6.1.1 -> 6.1.1.0
}

function Get-CandidateVersion {
    <# Major.Minor.Patch of a version tag, or $null for edge. #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string] $Candidate)
    Assert-Candidate $Candidate
    if ($Candidate -eq 'edge') { return $null }
    return [version]($Candidate.Substring(1) -replace '-.*$', '')
}

function Get-StableTag {
    <# The stable release tags (vX.Y.Z, no suffix) among $Tags, highest first. #>
    [CmdletBinding()]
    [OutputType([string[]])]
    param([string[]] $Tags = @())
    @($Tags | Where-Object { $_ -match '^v\d+\.\d+\.\d+$' } |
        Sort-Object { [version]$_.Substring(1) } -Descending)
}

function Get-PreviousStableTag {
    <#
    .SYNOPSIS
        The stable release a candidate upgrades FROM.
    .DESCRIPTION
        The highest stable tag strictly below the candidate's version: for
        v6.1.2-beta.1 and v6.1.2 that is v6.1.1, for v6.2.0-beta.1 it is the
        newest 6.1.x. A stable tag of the same version as a pre-release is
        excluded too, because 6.2.0-beta.1 precedes 6.2.0. For edge it is the
        newest stable tag. Throws when there is none: an upgrade test without a
        starting point would pass without testing anything.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory)][string] $Candidate,
        [string[]] $Tags = @()
    )
    $version = Get-CandidateVersion $Candidate
    $stable = Get-StableTag $Tags
    $below = @(if ($null -eq $version) { $stable } else { $stable | Where-Object { [version]$_.Substring(1) -lt $version } })
    if ($below.Count -eq 0) { throw "No stable release tag below '$Candidate' to upgrade from." }
    return $below[0]
}

function Get-ComposeRef {
    <# The git ref whose docker-compose.prod.yml belongs with a candidate. #>
    [CmdletBinding()]
