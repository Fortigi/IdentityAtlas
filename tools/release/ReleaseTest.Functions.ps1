        '/sync-log', '/categories', '/tags', '/access-packages', '/openapi.json'
    )
}

function Invoke-SmokeTest {
    <# GETs every smoke endpoint; returns the ones that did not answer 200. #>
    [CmdletBinding()]
    [OutputType([string[]])]
    param([Parameter(Mandatory)][string] $BaseUrl, [string] $Token = '')
    $failed = foreach ($ep in Get-SmokeEndpoint) {
        $code = Get-HttpStatus -Url "$BaseUrl$ep" -Token $Token
        if ($code -ne 200) { "$ep -> $code" }
    }
    @($failed)
}

function Get-IngestProbe {
    <#
    .SYNOPSIS
        One system, principal, resource and assignment to push through the
        ingest API, in call order.
    .DESCRIPTION
        The demo job already goes through the ingest API, but via the worker.
        This is the same path a crawler outside the stack takes, with the
        crawler API key, and it leaves rows the row-count comparison then has to
        carry through the upgrade.
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string] $SystemId)
    $common = @{ systemId = $SystemId; syncMode = 'delta'; idGeneration = 'deterministic' }
    @(
        @{ Path = '/ingest/principals'; Body = $common + @{ idPrefix = 'reltest-p'; records = @(@{ externalId = 'reltest-user-1'; displayName = 'Release Test User'; principalType = 'User'; accountEnabled = $true }) } }
        @{ Path = '/ingest/resources'; Body = $common + @{ idPrefix = 'reltest-r'; records = @(@{ externalId = 'reltest-res-1'; displayName = 'Release Test Group'; resourceType = 'Group'; enabled = $true }) } }
        @{ Path = '/ingest/resource-assignments'; Body = $common + @{ idPrefix = 'reltest-a'; records = @(@{ resourceExternalId = 'reltest-res-1'; principalExternalId = 'reltest-user-1'; assignmentType = 'Direct' }) } }
    )
}

function Invoke-IngestProbe {
    [CmdletBinding()]
    param([Parameter(Mandatory)][string] $BaseUrl, [Parameter(Mandatory)][string] $ApiKey)
    $system = Invoke-Api -BaseUrl $BaseUrl -Path '/ingest/systems' -Method Post -Token $ApiKey -Body @{
        syncMode = 'delta'
        records  = @(@{ displayName = 'Release Test System'; systemType = 'ReleaseTest'; enabled = $true; syncEnabled = $true })
    }
    $systemId = @(Get-Prop $system 'systemIds')[0]
    if (-not $systemId) { throw 'The ingest API returned no systemId.' }
    foreach ($call in Get-IngestProbe -SystemId $systemId) {
        Invoke-Api -BaseUrl $BaseUrl -Path $call.Path -Method Post -Token $ApiKey -Body $call.Body | Out-Null
    }
}

function Test-ReportGeneratorAnswer {
    <#
    .SYNOPSIS
        True when an /api/nl-reports/interpret reply is a real model answer.
    .DESCRIPTION
        'report' (a definition), 'clarify' (the model asks back) and 'confirm'
        (it wants a yes before running) all mean the model ran and its reply was
        understood. 'error' is a reply nobody could parse, and 'decline' to the
        plain question the test asks means the model is not answering properly;
        both fail, as does a missing reply.
    #>
    [CmdletBinding()]
    [OutputType([bool])]
    param($Reply)
    return ($null -ne $Reply) -and ((Get-Prop $Reply 'kind') -in 'report', 'clarify', 'confirm')
}

function Get-ApiTotal {
    <#
    .SYNOPSIS
        What the API reports as totals: users, resources, and the matrix's user count.
    .DESCRIPTION
        For deployments the test cannot query with psql (the portable ZIPs,
        Azure). Coarser than the Docker row counts, but read through the same
        endpoints the UI uses, so an upgrade that loses data shows here too.
    #>
    [CmdletBinding()]
    [OutputType([hashtable])]
    param([Parameter(Mandatory)][string] $BaseUrl, [string] $Token = '')
    @{
        Users     = [long](Get-Prop (Invoke-Api -BaseUrl $BaseUrl -Path '/users?limit=1' -Token $Token) 'total')
        Resources = [long](Get-Prop (Invoke-Api -BaseUrl $BaseUrl -Path '/resources?limit=1' -Token $Token) 'total')
        Matrix    = [long](Get-Prop (Invoke-Api -BaseUrl $BaseUrl -Path '/permissions?userLimit=1' -Token $Token) 'totalUsers')
    }
}

