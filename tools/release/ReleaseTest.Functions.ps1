function Compare-RowCount {
    <#
    .SYNOPSIS
        What changed between two row-count snapshots, as readable problems.
    .DESCRIPTION
        Strict tables must match exactly; grow-only tables must not shrink. A
        table in $Before that is missing from $After is always a problem. A
        table that only exists in $After is new in this version and ignored.
        An empty $Before is itself a problem: comparing against nothing proves
        nothing.
    #>
    [CmdletBinding()]
    [OutputType([string[]])]
    param(
        [Parameter(Mandatory)][hashtable] $Before,
        [Parameter(Mandatory)][hashtable] $After
    )
    if ($Before.Count -eq 0) { return @('no row counts were taken before the change') }
    $problems = foreach ($table in ($Before.Keys | Sort-Object)) {
        Get-RowCountProblem -Table $table -Before $Before[$table] -After $After
    }
    @($problems | Where-Object { $_ })
}

function Get-RowCountProblem {
    [CmdletBinding()]
    param([string] $Table, [long] $Before, [hashtable] $After)
    if (-not $After.ContainsKey($Table)) { return "$Table is gone (had $Before rows)" }
    $now = [long]$After[$Table]
    if ($script:GrowOnlyTables -contains $Table) {
        if ($now -lt $Before) { return "$Table shrank from $Before to $now rows" }
        return $null
    }
    if ($now -ne $Before) { return "$Table changed from $Before to $now rows" }
    return $null
}

function Get-CoreTable {
    [CmdletBinding()]
    [OutputType([string[]])]
    param()
    @($script:StrictTables + $script:GrowOnlyTables)
}

function Assert-DataLoaded {
    <# Fails when the counts show that the demo data did not arrive. #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][hashtable] $Counts)
    $empty = @('Principals', 'Resources', 'ResourceAssignments' | Where-Object { -not $Counts[$_] })
    if ($empty.Count -gt 0) { throw "No rows in $($empty -join ', ') after loading the demo data." }
}

function Wait-Until {
    <#
    .SYNOPSIS
        Calls $Condition until it returns a truthy value or $TimeoutSec passes.
    .DESCRIPTION
        Exceptions from $Condition count as "not yet" (a container that is still
        starting refuses connections). Returns the truthy value. Throws with
        $Description on timeout.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][scriptblock] $Condition,
        [Parameter(Mandatory)][string] $Description,
        [int] $TimeoutSec = 300,
        [int] $IntervalSec = 3
    )
    $deadline = (Get-Date).AddSeconds($TimeoutSec)
    do {
        $result = try { & $Condition } catch { $null }
        if ($result) { return $result }
        Start-Sleep -Seconds $IntervalSec
    } while ((Get-Date) -lt $deadline)
    throw "Timed out after $TimeoutSec s waiting for $Description."
}

function Invoke-Api {
    <# Invoke-RestMethod with the release test's defaults. #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string] $BaseUrl,
        [Parameter(Mandatory)][string] $Path,
        [string] $Method = 'Get',
        $Body = $null,
        [string] $Token = '',
        [int] $TimeoutSec = 60
    )
    $params = @{ Uri = "$BaseUrl$Path"; Method = $Method; TimeoutSec = $TimeoutSec; ErrorAction = 'Stop' }
    if ($Token) { $params.Headers = @{ Authorization = "Bearer $Token" } }
    if ($null -ne $Body) {
        $params.ContentType = 'application/json'
        $params.Body = $Body | ConvertTo-Json -Depth 10
    }
    Invoke-RestMethod @params
}

function Get-HttpStatus {
    <# The status code of a GET, without throwing on 4xx/5xx. 0 = no answer. #>
    [CmdletBinding()]
    [OutputType([int])]
    param([Parameter(Mandatory)][string] $Url, [string] $Token = '')
    $headers = @{}
    if ($Token) { $headers.Authorization = "Bearer $Token" }
    try {
        $r = Invoke-WebRequest -Uri $Url -Headers $headers -TimeoutSec 60 -SkipHttpErrorCheck -ErrorAction Stop
        return [int]$r.StatusCode
    } catch {
        return 0
    }
}

function Wait-SchemaReady {
    <# /api/health answers schemaReady:true once the migrations are done. #>
    [CmdletBinding()]
    param([Parameter(Mandatory)][string] $BaseUrl, [int] $TimeoutSec = 600)
    Wait-Until -Description "schemaReady at $BaseUrl/health" -TimeoutSec $TimeoutSec -IntervalSec 5 -Condition {
        (Get-Prop (Invoke-Api -BaseUrl $BaseUrl -Path '/health' -TimeoutSec 15) 'schemaReady') -eq $true
    } | Out-Null
}

function Invoke-DemoLoad {
    <#
    .SYNOPSIS
        Queues the demo crawler job and waits for it to finish, as the
        "Load Demo Data" button does. Throws if the job fails.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string] $BaseUrl,
        [string] $Token = '',
        [int] $TimeoutSec = 600
    )
    $job = Invoke-Api -BaseUrl $BaseUrl -Path '/admin/crawler-jobs' -Method Post -Body @{ jobType = 'demo' } -Token $Token
    $jobId = Get-Prop $job 'id'
    if (-not $jobId) { throw "The demo job was not queued: $($job | ConvertTo-Json -Compress)" }
    $status = Wait-Until -Description "demo job $jobId" -TimeoutSec $TimeoutSec -Condition {
        $s = Get-Prop (Invoke-Api -BaseUrl $BaseUrl -Path "/admin/crawler-jobs/$jobId" -Token $Token) 'status'
        if ($s -in 'completed', 'failed') { $s }
    }
    if ($status -ne 'completed') { throw "Demo job $jobId ended '$status'." }
}

